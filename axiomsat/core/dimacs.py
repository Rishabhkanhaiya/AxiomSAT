"""
DIMACS CNF Parser and Serializer for AxiomSAT.
Standard format used in SAT Competitions and formal verification.
"""

from pathlib import Path
from typing import Union, List
from .types import Formula, Clause, Literal


def parse_dimacs(source: Union[str, Path]) -> Formula:
    """
    Parses a DIMACS CNF file or string into an AxiomSAT Formula object.
    """
    if isinstance(source, Path) or (isinstance(source, str) and ("\n" not in source and Path(source).exists())):
        with open(source, "r", encoding="utf-8") as f:
            content = f.read()
    else:
        content = source

    formula = Formula(num_vars=0)
    expected_vars = 0
    expected_clauses = 0
    header_found = False

    current_clause_lits: List[Literal] = []

    for line in content.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("c"):
            formula.comments.append(line[1:].strip())
            continue
        if line.startswith("p"):
            parts = line.split()
            if len(parts) >= 4 and parts[1].lower() == "cnf":
                expected_vars = int(parts[2])
                expected_clauses = int(parts[3])
                formula.num_vars = expected_vars
                header_found = True
            continue

        # Clause lines (tokens separated by spaces, ending in 0)
        tokens = line.split()
        for tok in tokens:
            val = int(tok)
            if val == 0:
                if current_clause_lits:
                    formula.add_clause(current_clause_lits)
                    current_clause_lits = []
            else:
                current_clause_lits.append(val)

    if current_clause_lits:
        formula.add_clause(current_clause_lits)

    return formula


def write_dimacs(formula: Formula, path: Union[str, Path, None] = None) -> str:
    """
    Serializes a Formula into DIMACS CNF format string.
    Optionally writes to a file path.
    """
    lines = []
    lines.append("c ----------------------------------------------------------------")
    lines.append("c Generated by AxiomSAT - Formal Methods & Algorithmic Graph Theory")
    lines.append("c ----------------------------------------------------------------")
    for comment in formula.comments:
        lines.append(f"c {comment}")

    lines.append(f"p cnf {formula.num_vars} {len(formula.clauses)}")

    for clause in formula.clauses:
        lits_str = " ".join(str(lit) for lit in clause.literals)
        lines.append(f"{lits_str} 0")

    result = "\n".join(lines) + "\n"

    if path is not None:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(result)

    return result
